def api(path, method="GET", body=None):
    root = "https://skdorokhinmamalyshev.youtrack.cloud"
    data = None if body is None else json.dumps(body, ensure_ascii=False).encode()
    request = urllib.request.Request(
        root + path,
        data=data,
        method=method,
        headers={"Authorization": "Bearer " + os.environ["YOUTRACK_TOKEN"], "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def main():
    path = "/api/issues?" + urllib.parse.urlencode(
        {"query": "project: DPRO Type: Task", "fields": "idReadable,summary,description", "$top": 250}
    )
    issues = {issue["summary"]: issue for issue in api(path)}
    changed = 0
    for (_, block), criteria in zip(PLAN, CRITERIA, strict=True):
        titles = [line.split("|", 1)[1] for line in block.splitlines()]
        criteria_lines = criteria.splitlines()
        assert len(titles) == len(criteria_lines), (len(titles), len(criteria_lines))
        for title, criterion in zip(titles, criteria_lines, strict=True):
            issue = issues[title]
            description = (
                f"Результат: {title[0].lower() + title[1:]} .\n\n"
                f"Критерий приёмки: {criterion}\n\n"
                "После выполнения приложить ссылку на результат или проверку в задаче."
            ).replace(" .", ".")
            if issue.get("description") != description:
                api(f"/api/issues/{issue['idReadable']}?fields=idReadable", "POST", {"description": description})
                changed += 1
    print("Updated descriptions:", changed)


if __name__ == "__main__":
    main()
